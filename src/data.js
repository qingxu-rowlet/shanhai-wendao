function expNeed(L){ return L===0 ? 20 : L<9 ? 40+L*25 : L===9 ? 320 : 400+(L-10)*150; }
function statsFor(L){
  const z=L>=10?1:0;
  return {hp:Math.round(50+15*L+z*60), mp:Math.round(16+4*L+z*12), atk:Math.round(6+2.2*L+z*5), def:Math.round(1+0.8*L+z*2)};
}

